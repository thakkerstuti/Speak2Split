import cron from "node-cron";
import { RecurringExpenseModel } from "../db/models/RecurringExpense";
import { ExpenseModel } from "../db/models/Expense";
import { GroupMemberModel } from "../db/models/Group";
import { ActivityEventModel } from "../db/models/ActivityEvent";
import { calculateSplit } from "@speak2split/shared";
import { advanceOccurrence } from "./recurring.router";
import { broadcastToGroup } from "../realtime/socket";

/**
 * Generates all due recurring expenses. Runs on a schedule (see
 * startRecurringScheduler) and is also exported directly so it can be
 * invoked on-demand from a test or an admin endpoint without waiting for
 * the cron tick.
 *
 * Exactly-once generation, even across partial failures and concurrent runs:
 *  1. The expense insert is guarded by a unique index on
 *     (recurringExpenseId, recurringOccurrenceDate). A second insert for the
 *     same occurrence throws E11000 instead of double-billing.
 *  2. A duplicate-key error therefore means "this occurrence already exists"
 *     (e.g. a previous run inserted the expense but crashed or failed before
 *     advancing the schedule). Instead of swallowing it and leaving the
 *     schedule stuck forever, we treat the occurrence as done and advance.
 *  3. The schedule is advanced with a compare-and-set on nextOccurrence, so
 *     two concurrent runners can never advance the same occurrence twice.
 *  4. Any other failure (insert or advance) leaves nextOccurrence unchanged;
 *     the next run retries, and step 2 makes that retry safe.
 */
export interface RecurringRunResult {
  /** New expenses inserted this run. */
  generated: number;
  /** Occurrences that already existed (earlier partial failure / concurrent run) and were advanced past. */
  recovered: number;
  /** Schedules paused because a payer/participant left the group. */
  paused: number;
  /** Failures left for the next run to retry. */
  errors: number;
}

const isDuplicateKeyError = (err: unknown) => (err as { code?: number })?.code === 11000;

export async function runRecurringGeneration(): Promise<RecurringRunResult> {
  const due = await RecurringExpenseModel.find({
    isActive: true,
    nextOccurrence: { $lte: new Date() },
    $or: [{ endDate: { $exists: false } }, { endDate: { $gte: new Date() } }],
  });

  const result: RecurringRunResult = { generated: 0, recovered: 0, paused: 0, errors: 0 };

  for (const row of due) {
    try {
      const payers = row.payerConfig as { userId: string; amountPaid: number }[];
      const participants = row.participantConfig as { userId: string }[];

      // People may have left the group since the schedule was created. Never
      // generate an expense involving a non-member: pause the schedule instead
      // so a member can review it (and it stops retrying every hour).
      const activeIds = new Set(
        (await GroupMemberModel.find({ groupId: row.groupId, status: "ACTIVE" }).lean()).map((m) => String(m.userId))
      );
      const referenced = [...payers.map((p) => String(p.userId)), ...participants.map((p) => String(p.userId)), String(row.createdById)];
      if (referenced.some((id) => !activeIds.has(id))) {
        await RecurringExpenseModel.updateOne({ _id: row._id }, { $set: { isActive: false } });
        result.paused++;
        // eslint-disable-next-line no-console
        console.warn(`Recurring expense ${row._id} paused: a payer/participant is no longer an active group member.`);
        continue;
      }

      const occurrence: Date = new Date(row.nextOccurrence);
      const occurrenceDate = occurrence.toISOString().slice(0, 10);

      // 1) Insert the occurrence's expense (idempotent via the unique index).
      let expense: any = null;
      try {
        const split = calculateSplit(row.amount, row.splitMethod, payers, participants);
        expense = await ExpenseModel.create({
          groupId: row.groupId,
          title: row.title,
          amount: row.amount,
          currency: row.currency,
          category: row.category,
          splitMethod: row.splitMethod,
          source: "RECURRING",
          expenseDate: occurrence,
          createdById: row.createdById,
          recurringExpenseId: row._id,
          recurringOccurrenceDate: occurrenceDate,
          payers: split.payers,
          participants: split.participants,
        });
      } catch (err) {
        if (!isDuplicateKeyError(err)) throw err;
        // Already generated by an earlier (partially failed) or concurrent run.
      }

      // 2) Advance the schedule only if nobody else already did (compare-and-set).
      const advanced = await RecurringExpenseModel.updateOne(
        { _id: row._id, nextOccurrence: occurrence },
        { $set: { nextOccurrence: advanceOccurrence(occurrence, row.frequency), lastGeneratedAt: new Date() } }
      );

      if (!expense) {
        result.recovered++;
        // eslint-disable-next-line no-console
        console.warn(
          `Recurring expense ${row._id}: occurrence ${occurrenceDate} already existed; schedule ${
            advanced.modifiedCount ? "advanced" : "was already advanced"
          }.`
        );
        continue;
      }

      result.generated++;
      // Side effects are best-effort: the expense and schedule are already consistent.
      try {
        await ActivityEventModel.create({
          groupId: row.groupId,
          actorId: row.createdById,
          expenseId: expense._id,
          type: "recurring_expense_created",
          metadata: { title: expense.title, amount: expense.amount },
        });
        broadcastToGroup(String(row.groupId), "recurring_expense_created", {
          expenseId: String(expense._id),
          title: expense.title,
        });
      } catch (sideEffectErr) {
        // eslint-disable-next-line no-console
        console.error(`Recurring expense ${row._id}: activity/broadcast failed:`, sideEffectErr);
      }
    } catch (err) {
      // Nothing was advanced, so the next run retries this occurrence; the
      // unique index + duplicate handling above make that retry safe.
      // eslint-disable-next-line no-console
      console.error(`Recurring generation failed for ${row._id}:`, err);
      result.errors++;
    }
  }

  return result;
}

export function startRecurringScheduler() {
  // Every hour — recurring expenses are day/week/month granularity, so
  // hourly is frequent enough to feel real-time without hammering the DB.
  cron.schedule("0 * * * *", () => {
    runRecurringGeneration().catch((err) => {
      // eslint-disable-next-line no-console
      console.error("Recurring scheduler tick failed:", err);
    });
  });
}
